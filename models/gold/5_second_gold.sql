WITH participant_data AS (
    SELECT * FROM {{ ref('silver_integrated_participant') }}
),
session_data AS (
    SELECT * FROM {{ ref('silver_integrated_session') }}
),
time_windows AS (
    SELECT DISTINCT
    participation_id,
    to_timestamp(floor(date_part('epoch',timestamp)/5)*5) AS window_start,
    to_timestamp(floor(date_part('epoch',timestamp)/5)*5+4) AS window_end,
    FROM {{ ref('silver_integrated_emotions') }}
),
biosignals_data AS (
    SELECT 
    participation_id,
    CAST(MIN(timestamp) AS TIME) AS start_time,
    CAST(MAX(timestamp) AS TIME) AS end_time,
    MIN(CAST(timestamp AS DATE)) AS experiment_date,
    SUM(gsr) AS sum_gsr,
    SUM(record_count) AS count_gsr,
    ROUND((sum_gsr/count_gsr),2) AS avg_gsr,
    SUM(ppg) AS sum_ppg,
    SUM(record_count) AS count_ppg,
    ROUND((sum_ppg/count_ppg),2) AS avg_ppg,
    SUM(hr) AS sum_hr,
    SUM(record_count) AS count_hr,
    ROUND((sum_hr/count_hr),2) AS avg_hr
    FROM {{ ref('silver_integrated_biosignals') }}
    GROUP BY participation_id
),
blendshapes_data AS (
    SELECT
    participation_id,
    SUM(CASE WHEN blendshape_browDownLeft > 0.1 THEN 1 ELSE 0 END) AS bs_brow_down_left_seconds,
    SUM(CASE WHEN blendshape_browDownRight > 0.1 THEN 1 ELSE 0 END) AS bs_brow_down_right_seconds,
    SUM(CASE WHEN blendshape_browInnerUp > 0.1 THEN 1 ELSE 0 END) AS bs_brow_inner_up_seconds,
    SUM(CASE WHEN blendshape_browOuterUpLeft > 0.1 THEN 1 ELSE 0 END) AS bs_brow_outer_up_left_seconds,
    SUM(CASE WHEN blendshape_browOuterUpRight > 0.1 THEN 1 ELSE 0 END) AS bs_brow_outer_up_right_seconds,
    SUM(CASE WHEN blendshape_cheekPuff > 0.1 THEN 1 ELSE 0 END) AS bs_cheek_puff_seconds,
    SUM(CASE WHEN blendshape_cheekSquintLeft > 0.1 THEN 1 ELSE 0 END) AS bs_cheek_squint_left_seconds,
    SUM(CASE WHEN blendshape_cheekSquintRight > 0.1 THEN 1 ELSE 0 END) AS bs_cheek_squint_right_seconds,
    SUM(CASE WHEN blendshape_eyeBlinkLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_blink_left_seconds,
    SUM(CASE WHEN blendshape_eyeBlinkRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_blink_right_seconds,
    SUM(CASE WHEN blendshape_eyeLookDownLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_down_left_seconds,
    SUM(CASE WHEN blendshape_eyeLookDownRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_down_right_seconds,
    SUM(CASE WHEN blendshape_eyeLookInLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_in_left_seconds,
    SUM(CASE WHEN blendshape_eyeLookInRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_in_right_seconds,
    SUM(CASE WHEN blendshape_eyeLookOutLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_out_left_seconds,
    SUM(CASE WHEN blendshape_eyeLookOutRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_out_right_seconds,
    SUM(CASE WHEN blendshape_eyeLookUpLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_up_left_seconds,
    SUM(CASE WHEN blendshape_eyeLookUpRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_look_up_right_seconds,
    SUM(CASE WHEN blendshape_eyeSquintLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_squint_left_seconds,
    SUM(CASE WHEN blendshape_eyeSquintRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_squint_right_seconds,
    SUM(CASE WHEN blendshape_eyeWideLeft > 0.1 THEN 1 ELSE 0 END) AS bs_eye_wide_left_seconds,
    SUM(CASE WHEN blendshape_eyeWideRight > 0.1 THEN 1 ELSE 0 END) AS bs_eye_wide_right_seconds,
    SUM(CASE WHEN blendshape_jawForward > 0.1 THEN 1 ELSE 0 END) AS bs_jaw_forward_seconds,
    SUM(CASE WHEN blendshape_jawLeft > 0.1 THEN 1 ELSE 0 END) AS bs_jaw_left_seconds,
    SUM(CASE WHEN blendshape_jawOpen > 0.1 THEN 1 ELSE 0 END) AS bs_jaw_open_seconds,
    SUM(CASE WHEN blendshape_jawRight > 0.1 THEN 1 ELSE 0 END) AS bs_jaw_right_seconds,
    SUM(CASE WHEN blendshape_mouthClose > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_close_seconds,
    SUM(CASE WHEN blendshape_mouthDimpleLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_dimple_left_seconds,
    SUM(CASE WHEN blendshape_mouthDimpleRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_dimple_right_seconds,
    SUM(CASE WHEN blendshape_mouthFrownLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_frown_left_seconds,
    SUM(CASE WHEN blendshape_mouthFrownRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_frown_right_seconds,
    SUM(CASE WHEN blendshape_mouthFunnel > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_funnel_seconds,
    SUM(CASE WHEN blendshape_mouthLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_left_seconds,
    SUM(CASE WHEN blendshape_mouthLowerDownLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_lower_down_left_seconds,
    SUM(CASE WHEN blendshape_mouthLowerDownRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_lower_down_right_seconds,
    SUM(CASE WHEN blendshape_mouthPressLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_press_left_seconds,
    SUM(CASE WHEN blendshape_mouthPressRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_press_right_seconds,
    SUM(CASE WHEN blendshape_mouthPucker > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_pucker_seconds,
    SUM(CASE WHEN blendshape_mouthRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_right_seconds,
    SUM(CASE WHEN blendshape_mouthRollLower > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_roll_lower_seconds,
    SUM(CASE WHEN blendshape_mouthRollUpper > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_roll_upper_seconds,
    SUM(CASE WHEN blendshape_mouthShrugLower > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_shrug_lower_seconds,
    SUM(CASE WHEN blendshape_mouthShrugUpper > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_shrug_upper_seconds,
    SUM(CASE WHEN blendshape_mouthSmileLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_smile_left_seconds,
    SUM(CASE WHEN blendshape_mouthSmileRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_smile_right_seconds,
    SUM(CASE WHEN blendshape_mouthStretchLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_stretch_left_seconds,
    SUM(CASE WHEN blendshape_mouthStretchRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_stretch_right_seconds,
    SUM(CASE WHEN blendshape_mouthUpperUpLeft > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_upper_up_left_seconds,
    SUM(CASE WHEN blendshape_mouthUpperUpRight > 0.1 THEN 1 ELSE 0 END) AS bs_mouth_upper_up_right_seconds,
    SUM(CASE WHEN blendshape_neutral > 0.1 THEN 1 ELSE 0 END) AS bs_neutral_seconds,
    SUM(CASE WHEN blendshape_noseSneerLeft > 0.1 THEN 1 ELSE 0 END) AS bs_nose_sneer_left_seconds,
    SUM(CASE WHEN blendshape_noseSneerRight > 0.1 THEN 1 ELSE 0 END) AS bs_nose_sneer_right_seconds
    FROM {{ ref('silver_integrated_blendshapes') }}
    GROUP BY participation_id
),
emotions_data AS (
    SELECT
    participation_id,
    SUM(CASE WHEN UPPER(dominant) = 'HAPPY' THEN 1 ELSE 0 END) AS emotion_happy_seconds,
    SUM(CASE WHEN UPPER(dominant) = 'SAD' THEN 1 ELSE 0 END) AS emotion_sad_seconds,
    SUM(CASE WHEN UPPER(dominant) = 'ANGRY' THEN 1 ELSE 0 END) AS emotion_angry_seconds,
    SUM(CASE WHEN UPPER(dominant) = 'SURPRISE' THEN 1 ELSE 0 END) AS emotion_surprise_seconds,
    SUM(CASE WHEN UPPER(dominant) = 'DISGUST' THEN 1 ELSE 0 END) AS emotion_disgust_seconds,
    SUM(CASE WHEN UPPER(dominant) = 'NEUTRAL' THEN 1 ELSE 0 END) AS emotion_neutral_seconds,
    ROUND(emotion_happy_sum/record_count,2) AS emotion_happy_avg,
    ROUND(emotion_sad_sum/record_count,2) AS emotion_sad_avg,
    ROUND(emotion_angry_sum/record_count,2) AS emotion_angry_avg,
    ROUND(emotion_surprise_sum/record_count,2) AS emotion_surprise_avg,
    ROUND(emotion_disgust_sum/record_count,2) AS emotion_disgust_avg,
    ROUND(emotion_neutral_sum/record_count,2) AS emotion_neutral_avg,
    ROUND(confidence_sum/record_count,2) AS emotion_confidence_avg,
    MODE(dominant) AS emotion_dominant_overall
    FROM {{ ref('silver_integrated_emotions') }}
    GROUP BY participation_id
),
participation_data AS (
    SELECT * FROM {{ ref('silver_integrated_participation') }}
)

